/**
 * 回收站到期硬删的**时钟护栏** · F-015（2026-09-01）
 *
 * ── 它挡的是哪一种事故 ────────────────────────────────────
 *
 * 「打开回收站就把过期 30 天的东西硬删掉」是契约行为（D-087），
 * 而硬删会**立墓碑**，墓碑随同步推给另一端之后**不可撤销** ——
 * 这是整个系统里为数不多的、真正会让数据永久消失的动作。
 *
 * 而它此前只信一个数：`Date.now()`。
 * 本机时钟被调快（手动改、时区变、NTP 异常、双系统各写各的 RTC）的那一刻，
 * 打开回收站页就会把**还没到 30 天**的东西当场删掉、立碑、推出去，
 * **两端都永久没了**，而且全程不报错。
 *
 * ── 为什么判据长这样 ──────────────────────────────────────
 *
 * 系统里没有第三方时钟可以裁决（store 是哑的 blob 存储，没有服务端时钟）。
 * 唯一的外部参照就是**别的设备写的行上带的时间戳** —— 同步引擎已经在
 * 观测它了（`sync/engine.ts` 的 `maxRemoteAt`），只是从来没存下来。
 *
 * 所以判据是「本机时钟和另一台机器写下的最新时刻差得离谱吗」：
 *
 *   · 本机 **落后** 远端很多  → 本机时钟慢（或者刚拿到一批很新的数据）。
 *     这个方向**不危险** —— cutoff 会算得更早，只会少删，不会多删。放行。
 *   · 本机 **超前** 远端很多  → 本机时钟很可能被调快了。这个方向会**多删**。
 *     拒绝这次清除。
 *
 * ★★ 拒绝的后果只是「这次没清」—— 东西还在回收站里，下次时钟正常了自然会清。
 *    **安全的方向是不删。** 这条闸不需要精确，只需要不误伤。
 *
 * ── 为什么阈值这么松 ──────────────────────────────────────
 *
 * 两台设备时间差几分钟是完全正常的（离线漂移、时区、校时延迟），
 * 而且 30 天的保留期本身就有巨大冗余：真要误删，时钟得快到把
 * 「删了不到 30 天」算成「超过 30 天」，也就是**至少快好几天**。
 * 所以阈值取 7 天 —— 比噪声大得多，比伤害小得多。
 * 阈值取小了这条闸会天天亮，而天天亮的闸最后一定会被人绕过去，那比没有闸更糟。
 *
 * ★ 没有远端参照时（从没同步过、单机用）**放行** —— 不能因为「没证据」
 *   就把一个正常功能停掉。这条闸的作用是「有证据表明时钟错了就别删」，
 *   不是「证明时钟对了才准删」。
 *
 * ══ ★★★ I-188 · 一个条件，**两种成因**，所以那句话不许只说一种 ══
 *   （2026-09-15，Nyx-UI-Android 核出；判据方向经复核**不动**）
 *
 * `now − maxRemoteSeen > 容差` 触发时，真相有两种，而且从桶里**分不开**：
 *
 *   ① 本机的钟被拨快了 —— 危险的那一种（会多删），正是这条闸要挡的；
 *   ② **对端干脆好久没同步** —— `maxRemoteSeen` 是对端最后一次改动的时间戳，
 *      对端不动它就不动。这一种里本机的钟一点问题都没有。
 *
 * 所以拦是对的（拿不准就别做不可撤销的事），**但下断言是错的**。
 * 原来那句话写的是「看起来本机时钟不太对」，还把方向说反了 ——
 * 触发条件明明是本机比远端**晚**，句子却说「本机时间……早了」。
 * 他照着去调钟，只会把偏差调得更大。
 *
 * ★ 现在的写法：**两种成因都摆出来，一个都不判定**。
 *   文案和判定同向是硬要求（和启动页改名那条 X-1 同一课）：
 *   判据分不开的两件事，文案也不许替它分。
 *
 * ★★ 容差 7 天 —— **使用者 2026-09-15 当面裁「不放宽」**（主控推荐留 7 天，他点了头）。
 *   留档的理由：文案说了真话之后，「这次先不清」本身不伤人；而放宽到 30 天意味着
 *   **本机快 29 天也照样放行**，会把昨天才丢进回收站的东西永久删掉 ——
 *   这条闸挡的正是「永久且不可撤销」，宁可多拦一次。
 *   ★ 这是**他裁过的数**，不是随手挑的默认值。要改先回去问他，别当成可调参数顺手动。
 */

/** 本机比远端见过的最新时刻超前多少才叫「不对劲」 */
export const PURGE_SKEW_LIMIT_MS = 7 * 24 * 60 * 60 * 1000

export interface PurgeGuardInput {
  /** 本机当前时刻 */
  now: number
  /** 同步时见过的最大远端 `updated_at`（`settings['sync.maxRemoteSeen']`）；没有就 0 */
  maxRemoteSeen: number
  /** 容差，默认 {@link PURGE_SKEW_LIMIT_MS} */
  toleranceMs?: number
}

export interface PurgeGuardVerdict {
  /** 允许这次到期清除吗 */
  ok: boolean
  /** 不允许时给一句人话（放行时为 null）—— 直接进 `sync.problems`，不弹窗 */
  why: string | null
  /** 观测到的超前量（毫秒），放行时也算得出来，供留痕 */
  aheadMs: number
}

export function purgeAllowed(input: PurgeGuardInput): PurgeGuardVerdict {
  const tol = input.toleranceMs ?? PURGE_SKEW_LIMIT_MS
  const seen = input.maxRemoteSeen

  // 没有远端参照 —— 没证据，放行（见文件头最后一段）
  if (!Number.isFinite(seen) || seen <= 0) return { ok: true, why: null, aheadMs: 0 }

  const ahead = input.now - seen
  if (ahead <= tol) return { ok: true, why: null, aheadMs: Math.max(0, ahead) }

  const days = Math.round(ahead / 86_400_000)
  return {
    ok: false,
    aheadMs: ahead,
    why:
      `这次先没清理回收站里到期的：另一台设备已经约 ${days} 天没同步过，或者本机时间快了；` +
      `到期清理会永久删除并同步过去，所以拿不准就先不清。回收站里的东西一样没少。`
  }
}
