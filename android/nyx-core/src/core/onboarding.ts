/**
 * 要不要出引导。
 *
 * @param doneAt 库里 `ONBOARDING_KEY` 那一行的值。**没设过时是空串**
 *   （`ui:get` 读不出来给空串，不是 null —— 这是那条通道的约定）。
 *
 * ★★ **看完和跳过都算看过**（派单 §边界）—— 所以这里只认「有没有值」，
 *   不认「看到第几步」。存「看到第几步」的话就得决定「看了 3 步算不算看过」，
 *   而那个问题没有好答案：他跳过就是不想看，再弹一次是不尊重他的选择。
 * ★ 坏值（乱码 · 负数 · 0）当**没看过**：宁可多出一次引导，
 *   也不要因为一个读不懂的值让他永远见不到它。
 */
export function shouldOnboard(doneAt: string | number | null | undefined): boolean {
  if (doneAt === null || doneAt === undefined) return true
  const n = typeof doneAt === 'number' ? doneAt : Number(String(doneAt).trim())
  if (!Number.isFinite(n) || n <= 0) return true
  return false
}

