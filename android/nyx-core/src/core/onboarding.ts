export const guideById = (id: string): GuideDef | null =>
  PAGE_GUIDES.find((g) => g.id === id) ?? null

/** 「看过」表的形状：`{ 引导 id: 看过时那一条的 version }` */
export type GuideSeen = Record<string, number>

/**
 * 读那张表。**坏值一律当没看过**，绝不抛 —— 抛了的话整页都打不开，
 * 而这一层本来就只是「多说一句话」。
 *
 * ★★ **不设上界、不丢最旧**（确认单表 D）：它至多 8 条，而「看过」被挤掉的后果是
 *   同一句话再弹一次 —— 那正是这一层最该避免的事（烦人）。
 *   和 `reading.lastFace` 那张有界 map 不是一回事：那一张按知识点存，会随库长。
 */
export function parseGuideSeen(raw: string | null | undefined): GuideSeen {
  if (typeof raw !== 'string' || raw.trim() === '') return {}
  let parsed: unknown = null
  try {
    parsed = JSON.parse(raw)
  } catch {
    return {}
  }
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) return {}
  const out: GuideSeen = {}
  for (const [k, v] of Object.entries(parsed as Record<string, unknown>)) {
    if (typeof v === 'number' && Number.isFinite(v)) out[k] = v
  }
  return out
}

/** 记一笔「这一条看过了」，记的是**当时那一条的 version** */
export function noteGuideSeen(raw: string | null | undefined, id: string, version: number): string {
  const seen = parseGuideSeen(raw)
  seen[id] = version
  return JSON.stringify(seen)
}

/**
 * ★★★ 这一条现在要不要出。
 *
 *   没看过            → 出
 *   看过、版本没变     → 不出
 *   看过、但内容 +1 了 → **只有这一条**重出一次（使用者第六条）
 *
 * ★ 认不出的 id 一律不出：名单在 core，界面传了个不在名单里的 id，
 *   那是**代码写错了**，不该表现成「屏幕上多出一句没人认领的话」。
 */
export function shouldShowGuide(
  seen: GuideSeen,
  id: string,
  version: number = guideById(id)?.version ?? 0
): boolean {
  if (!guideById(id)) return false
  const at = seen[id]
  if (typeof at !== 'number') return true
  return at < version
}
