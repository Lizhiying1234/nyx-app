/**
 * 查词时问 AI 用的那段提示词 · 两端共用（使用者 2026-09-13）
 *
 * 他的原话：「这个功能不要再只是单纯调用词典，希望它的功能与 Glance 对齐，
 * 进入后能够统一提供：词典 · AI · 语音……**不要再让『查字典』和其他查词能力
 * 成为彼此割裂的功能**。」
 *
 * ══ 为什么不新起一条提示词 ═════════════════════════════════════
 * 名册里**已经有 `lookup-search`**（`core/prompt-overrides.ts`），说的就是这件事 ——
 * 「Lookup 的 AI 搜索」。它一直标着 `scope: 'android'`，理由写在那儿：
 * 「Windows 没有 Lookup 的 AI 搜索」。**今天有了。**
 * 所以这不是新功能要新提示词，是那条注释的前提变了 —— 改 scope，不加名字。
 * 新起一条的话，同一件事会有两份提示词，而他在设置里改了其中一份之后，
 * 另一端的行为不跟着变 —— **两边都说得通、都不报错**。
 *
 * ══ 为什么正文搬进 core（而不是留在 Android 的 lookup.ts）═══════
 * 和 `reading-card` 2026-09-03 那次一模一样的理由，那条注释原话：
 * 「各写一份的话，同一张卡在两台机器上考法不一样、红线松紧也不一样，
 *   而两边都说得通、都不报错。」
 * 查词同理：同一个词在电脑上和手机上讲法不同，他会以为是模型不稳定。
 *
 * ★ `builtin: 'code'` 不变 —— 默认正文在这里，不是 `prompts/*.md`。
 *   不走 md 的原因和牌面那条一样：md 那个格式要拆 `## SYSTEM` / `## USER` 两段，
 *   而这一段只有 system；硬套会让手机存下的那一整段在 Windows 上被当成 user 发出去。
 */

/**
 * ★★ 给什么就处理什么 —— 这一条是 2026-09-03 在手机上撞出来的。
 *
 * 老写法把用户给的东西一律叫「词」，于是他选了一整句，模型**从里面挑一个词讲**，
 * 然后当作已经回答了。那种回答**看着完全正常**，只有对着原句读才发现答非所问。
 */
export const SHAPE_RULE =
  '用户给的可能是一个词、一个词组、一整句话，也可能是一段连续文字。' +
  '**给你什么就处理什么**：是词或词组就按词条讲；' +  // copy:prompt
  '是整句或整段，就讲这一整段 —— 先说它整体在讲什么，' +
  '再点出里面真正难的那一两处（结构、搭配、语气），' +
  '**绝对不要只挑其中一个词讲，然后当作已经回答了**。'

/**
 * 「查词 → 问 AI」的默认提示词。
 * ★ 存进 `user_preferences['prompt.lookup-search']` 的才算数，这里只是没配时的兜底。
 * ★ 逐字沿用手机上跑了一个月的那一份 —— 不趁搬家顺手改文案：
 *   改了的话，他会觉得「电脑上讲得和手机不一样」，而那正是这次搬进 core 要消灭的事。
 */
export const DEFAULT_LOOKUP_PROMPT =
  '你是给中文母语者用的英语助手。用户主动查一段英文，没有上下文。' +
  SHAPE_RULE +
  '按这些小节组织：释义（中文；词/词组把常见义项按使用频率排、各给一句话，' +
  '整句整段就说这一整段的意思）、' +
  '用法（词性 · 常见搭配 · 语域；整句整段讲结构与关键搭配）、' +
  '例句（两句地道例句，各附中文翻译）、' +
  '辨析（和哪些近义表达容易混，怎么分；没有就省略）。' +  // copy:prompt
  '小节标题独占一行。直接给内容，不要寒暄，不要重复用户输入的原文。'

/**
 * 送给模型的那一句「这是什么形态」。
 *
 * ★ 2026-09-03 手机上改过一次：老写法是 `词：<原文>`，把一整句叫成「词」——
 *   于是模型从里面挑一个词讲。**原样送出，并且说清它是什么形态。**
 */
export function lookupUserMessage(text: string): string {
  const s = String(text ?? '').trim()
  const words = s.split(/\s+/).length
  const kind = s.length > 40 || words > 8 ? '这段文字' : words > 1 ? '这个词组' : '这个词'
  return `${kind}：${s}`
}

/**
 * ══ 词条顶部那两行（使用者 2026-09-13 第二轮）════════════════
 *
 * 他要的层级是：
 *   当前词条 ├── 音频 ├── AI 简短英文释义 ├── AI 简短中文释义（默认收起）
 *            └── AI | Dictionary
 * 也就是说这两行**不属于** AI 那一档，也不属于 Dictionary 那一档 ——
 * 它们是词条本身的信息，两个界面都在它们下面。
 *
 * ★ 为什么单独一条提示词、而不是从下面那整段解释里截一段：
 *   那一整段要跑五到八秒，而这两行是**他一眼要看的东西**。
 *   截出来的话，卡打开后好几秒是空的 —— 那等于没有「默认直接显示」。
 *   额度上也划算：这一条 160 token 顶天，那一条 1200。
 *
 * ★ 形状定死成两行带前缀，不是为了好看，是为了**分得开** ——
 *   模型回一段话的话，我没法判断哪半句是英文释义、哪半句是中文释义，
 *   而摆错位置比不摆更糟（他会以为那行英文就是中文释义的翻译）。
 */
export const DEFAULT_BRIEF_PROMPT =
  '你是给中文母语者用的英语助手。用户给你一段英文（可能是一个词、一个词组或一小句）。' +
  '只回两行，**每行都要有前缀**：' +
  '第一行 `EN: ` 后面跟一句**英文**的简短释义，不超过 18 个词，用英文解释它的意思；' +
  '第二行 `ZH: ` 后面跟一句**中文**的简短释义，不超过 30 个字，' +
  '多个常见义项用「；」分隔，最多三个。' +
  '不要标题、不要 Markdown、不要引号、不要例句、不要词性说明、不要重复用户给的原文、不要解释过程。' +
  '只输出这两行。'

/** 词条顶部那两行 */
export interface Brief {
  /** 简短英文释义（默认显示那一行）*/
  readonly en: string
  /** 简短中文释义（默认收起那一行）*/
  readonly zh: string
}

/** 剥掉行内 Markdown 噪音与引号 —— 只做减法，字不改 */
function tidy(s: string): string {
  return s
    .replace(/\*\*(.+?)\*\*/g, '$1')
    .replace(/\*(.+?)\*/g, '$1')
    .replace(/`(.+?)`/g, '$1')
    .replace(/^[「"'\u201c]+|[」"'\u201d]+$/g, '')
    .trim()
}

/**
 * 两行 → `{ en, zh }`。**绝不抛**，认不出来就给空串 ——
 * 这两行是附加信息，读不出来最多是那一行不显示，不该把整张卡带崩。
 *
 * ★ 前缀认得宽一点（`EN:` / `en：` / `英文：` / `英:`），因为**提示词是他能改的**；
 *   一个字都认不出来时退到「第一行当英文、第二行当中文」——
 *   ★ 但退之前要看一眼：第一行真的像英文吗？不像就**宁可空着**。
 *     摆错位置比不摆更糟：他会以为那行中文是英文释义。
 */
export function parseBrief(raw: unknown): Brief {
  /**
   * ★ 只认字符串。`String(raw)` 那种写法会把 `42` 变成一行「42」，
   *   而它是纯 ASCII —— 于是被当成**英文释义**摆到词条头上。
   *   和 `decodeMeta` / `decodeLabels` 同一条规矩：不是字符串就当没有。
   */
  if (typeof raw !== 'string') return { en: '', zh: '' }
  const t = raw
    .trim()
    .replace(/^```[a-z]*\r?\n?/i, '')
    .replace(/\r?\n?```$/, '')
  if (!t) return { en: '', zh: '' }
  let en = ''
  let zh = ''
  const rest: string[] = []
  for (const line0 of t.split(/\r?\n/)) {
    const line = tidy(line0.trim())
    if (!line) continue
    const m = /^(EN|ZH|英文|中文|英|中)\s*[:：]\s*(.+)$/i.exec(line)
    if (m) {
      const key = m[1]!.toLowerCase()
      const val = tidy(m[2]!)
      if (key === 'en' || key === '英文' || key === '英') en ||= val
      else zh ||= val
      continue
    }
    rest.push(line)
  }
  /** 一个前缀都没有 —— 按位置退，但只在「长得对」的时候退 */
  if (!en && !zh && rest.length > 0) {
    const first = rest[0]!
    const second = rest[1] ?? ''
    if (/^[\x00-\x7f\s]+$/.test(first)) {
      en = first
      zh = second
    } else {
      zh = first
    }
  } else if (!zh && rest.length > 0 && en) {
    zh = rest[0]!
  }
  return { en, zh }
}
