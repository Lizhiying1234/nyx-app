/**
 * 启动页画哪张图 —— **这两行就是那两个「可换的值」**（DS §12.0c）。
 *
 * ══ 2026-09-09 使用者裁「启动页只能保留一个」★★ ══════════════
 * 在这之前手机上是**两帧**：系统那一帧（水獭）+ 应用那一帧（插画）。
 * 使用者原话：「为什么先是小熊，然后是闪过了出厂插画，我记得我说过，
 * 启动页只能保留一个」——「以我的裁决为准，我就要 1 个」。
 *
 * 系统那一帧的图是**写死在 manifest 主题里的**，运行时换不了（起进程之前就画了）。
 * 所以「只留一张」只有两条路，选的是第二条：
 *   甲 · 让系统那一帧说了算 → 删掉应用帧，但「资源 › 启动页」在手机上就作废了
 *   乙 · **让应用那一帧说了算** → 系统帧退成纯水色不放图，水獭挪进应用帧当第一档
 * 结果：启动只出现**一张**图 —— 他选的那张。
 *
 * ★ 于是这里从「一个值」变成「两个值」：应用帧要能画水獭，而水獭原来只有原生资源
 *   （`mipmap/ic_launcher_foreground`），WebView 读不到 res/，所以按同一张源图
 *   在 web 资源里放一份。**不是第二份真相** —— 两份都是 `nyx-core/assets/brand` 那一张的产物。
 * ★ 手机上换图 = 重打包装机（这是手机的常态，不是缺陷）。
 * ★ 设成 `null` = 那一档没图：回退链会往下走一格，不会白屏。
 */
import art from '../assets/splash-illustration.webp'
import icon from '../assets/splash-icon.png'

/** 出厂那张插画 */
export const SPLASH_ART: string | null = art

/**
 * 应用图标那张（去瓷砖的水獭，透明底）—— 回退链的**最后一档，永远可用**。
 * ★ 画布 432×432，主体占宽 48.6% / 占高 62.7%，正中（量出来的，不是估的）。
 *   按 288px 画 = 系统那一帧图标画布（288dp）的同一组数 ——
 *   所以水獭的大小和位置和换之前**一模一样**，他不会觉得图突然变小了。
 */
export const SPLASH_ICON: string = icon
