/**
 * 「这一版我不要」—— 使用者的裁决，作为一条事实 · ★★ R-4-F-a
 *
 * ── 病 ──────────────────────────────────────────────────────
 *
 * R-4-F 让冲突不再劫持整条同步流水线，但他按下的那个决定**只靠
 * `applied`（最近 500 个包名）兜着**。那是一张去重缓存，不是事实：
 * 溢出、新设备、导回旧备份 —— 三条路都会让被拒绝的那一版重新出现。
 *
 * 而那时水位早已越过它，`decideRow` 落在最后那一格
 * 「两边都没新改动，取新的那个」。他选「用本地」的时候，
 * 云端那版**通常就是更新的那个**（「云端刚刚改的，本地 5 分钟前改的，用哪边？」），
 * 于是 take-remote —— 他明确拒绝过的内容悄悄盖掉了他留下的内容。
 *
 * ── 语义 ────────────────────────────────────────────────────
 *
 * `rejectedUpTo` = **到这个时刻为止**的远端版本，他都明确拒绝过。
 *
 *   remote.updatedAt <= rejectedUpTo  → 不再产生冲突，留本地的
 *   remote.updatedAt >  rejectedUpTo  → 那是对面之后的新改动，照常问他
 *
 * **不是「永久拒绝这个对象」。** 写成永久的话，两台机器从此再也无法
 * 就这一行达成一致：对面之后每一次正常修改都会被无声吞掉。
 *
 * ── 它绑在 uid 上，不绑在内容上 ─────────────────────────────
 *
 * 彻底删掉 X、再建一个看起来一模一样的 Y —— Y 是新 uid，
 * **X 的裁决一个字都不适用于它**（和 R-3 墓碑同一条纪律）。
 * 绝不按 term / name / content / derived_from 自动迁移：
 * 猜错的后果是他新写的东西被一条旧决定挡住，而且没有任何提示。
 */

export interface ResolutionFact {
  targetUid: string
  kind: string
  /** 到这个时刻为止的远端版本都被明确拒绝过 */
  rejectedUpTo: number
}

/**
 * 这一行的这个远端版本，是不是他已经拒绝过的那一版。
 *
 * **判据只有这一处。** 同步、体检、导回合并全都问它，
 * 不许谁再手写一遍 `<=` —— 两处判据迟早会分家，
 * 而分家的表现是「有时候挡得住、有时候挡不住」，谁都查不出规律。
 */
export function isResolutionBlocking(
  res: ResolutionFact | undefined,
  remoteUpdatedAt: number
): boolean {
  if (!res) return false
  return remoteUpdatedAt <= res.rejectedUpTo
}

/**
 * 裁决行自己的跨设备身份 —— **算出来的，不是随机的**。
 *
 * 两台机器对同一个对象各自裁决时，必须落在**同一个 uid** 上：
 * 随机 uid 会变成两行，而它们又撞在 `(target_uid, kind)` 那个唯一索引上，
 * 同步过去直接失败、永远重试。算出来就没有这回事。
 *
 * `target_uid` 本身已经带着表名前缀（`items-3f2a…`），所以这个串天然唯一。
 */
export function resolutionUid(targetUid: string): string {
  return `resolutions-${targetUid}`
}

/**
 * 这张表的两份数据**合并到一起**就行，没有「用哪边」的问题。
 *
 * `resolutions` 是目前唯一一张：它的合并规则是 `max`，
 * 由数据库触发器守着（V25），谁先谁后落库结果都一样。
 * 所以它永远不该走到冲突那一格 —— 那会让使用者看到一条
 * 他根本不认识的内部记录，而且不管选哪边结果都相同。
 *
 * **不要往这张名单里随手加表。** 能进来的判据只有一条：
 * 这张表的合并有一条**与顺序无关、且落在数据库里**的规则。
 */
export function isMonotoneRow(table: string): boolean {
  return table === 'resolutions'
}

/**
 * ★★ D5 · 选「用本地」之后，留下的那一行该盖什么时间戳。
 *
 * ── 为什么非顶不可 ──────────────────────────────────────────
 *
 * 他选「用本地」时，本地那版**常常比云端那版旧** —— 那正是他要做决定的原因。
 * 于是 `rejectedUpTo`（被拒那版的时间戳）**大于**留下那版的时间戳，
 * 而 `isResolutionBlocking` 只看时间戳，它分不出「这一版是被拒的」还是
 * 「这一版是留下的」。两个洞跟着出来：
 *
 *   · 第三台机器上，**留下的那一版**作为远端行到达时也 `<= rejectedUpTo`
 *     → 被自己的裁决挡掉 → 那台机器留着**被拒绝的那一版**
 *   · 谁赢取决于哪个包先到 —— 而包的顺序是推送时间，不是他的决定
 *
 * 顶一下之后，不变式成立：
 *
 *   **最终保留的本地版本  >  所有被拒绝的远端版本**
 *
 * 别的机器按**普通合并规则**就收敛，裁决事实只干它该干的那一件事：
 * 挡住旧包复活被拒的版本。
 *
 * `+1` 不能省：远端那一版和「现在」落在同一毫秒时，`==` 会被判成
 * `same` 或者仍然落在挡住的区间里，那个不变式就不成立了。
 *
 * ★ 它只动 `updated_at`。内容、`created_at`、`status`、学习进度、
 * `card_*`、`attempts` / `corrects` / `streak` 一个字都不许动 ——
 * 他按的是「用本地的」，不是「改这一行」。
 */
export function keptUpdatedAt(now: number, rejectedUpTo: number): number {
  return Math.max(now, rejectedUpTo + 1)
}
